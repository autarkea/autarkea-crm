// Гибрид, согласован с владельцем (04.09.2026):
//   Задачи активные/«на сегодня» — по «Когда делаем» asc: просроченные сверху
//     (самые старые из просроченных — первыми), БЕЗ срока — в конец (свежие сверху)
//   Задачи проекта — активные сверху (по сроку asc), затем выполненные (свежезакрытые)
//   История задач / Архив проектов — UpdatedAt desc (лента)
//   Контакты / Юрлица — алфавит (Имя, ru), пустые имена в конец
//   Проекты активные — «Готов к сдаче» → «В работе» → «Обсуждение», внутри по сроку
//
// Запуск (Node на хосте, без контейнеров и зависимостей):
//   node --test tests/
//
// Правило: меняешь компараторы в shared/sorting.js — этот файл должен остаться
// зелёным. Меняешь решённый порядок списков — сначала сюда.
// ============================================================================

const { test } = require('node:test');
const assert = require('node:assert/strict');

const s = require('../shared/sorting');

const ids = rows => rows.map(r => r.Id);

// ─────────────────────────── Задачи активные (дедлайн asc) ──────────────────
test('Активные задачи: просроченные (старые первыми) → по сроку → без срока в конце', () => {
    const tasks = [
        { Id: 10, 'Когда делаем': '2026-09-11T09:00:00+03:00' }, // через неделю
        { Id: 5,  'Когда делаем': '2026-08-01T09:00:00+03:00' }, // просрочена давно
        { Id: 8,  'Когда делаем': null },                        // без срока
        { Id: 9,  'Когда делаем': '2026-09-05T09:00:00+03:00' }, // ближайшая
        { Id: 6,  'Когда делаем': '2026-09-01T09:00:00+03:00' }, // просрочена недавно
        { Id: 3 }                                              // без срока (без поля)
    ];
    const order = tasks.slice().sort(s.compareTasksActive);
    assert.deepEqual(ids(order), [5, 6, 9, 10, 8, 3]);
});

test('Активные задачи: равный срок — выше новая (Id desc), сортировка детерминирована', () => {
    const tasks = [
        { Id: 5,  'Когда делаем': '2026-09-05T10:00:00+03:00' },
        { Id: 50, 'Когда делаем': '2026-09-05T10:00:00+03:00' }
    ];
    const a = tasks.slice().sort(s.compareTasksActive);
    const b = tasks.slice().reverse().sort(s.compareTasksActive);
    assert.deepEqual(ids(a), [50, 5]);
    assert.deepEqual(ids(b), [50, 5]);
});

test('Без срока — всегда в конец, внутри — свежие сверху', () => {
    const tasks = [
        { Id: 4 },                         // нет поля вовсе
        { Id: 40, 'Когда делаем': '' },    // пустая строка
        { Id: 1,  'Когда делаем': '2026-10-01T09:00:00+03:00' }
    ];
    const order = tasks.slice().sort(s.compareTasksActive);
    assert.deepEqual(ids(order), [1, 40, 4]);
});

// ─────────────────────────── Задачи проекта ─────────────────────────────────
test('Задачи проекта: активные (по сроку) сверху, затем выполненные (свежезакрытые)', () => {
    const tasks = [
        { Id: 30, Готово: true,  UpdatedAt: '2026-09-04T10:00:00+03:00' }, // закрыта свежее
        { Id: 40, Готово: true,  UpdatedAt: '2026-09-03T10:00:00+03:00' }, // закрыта раньше
        { Id: 1,  Готово: false, 'Когда делаем': '2026-09-10T10:00:00+03:00' },
        { Id: 2,  Готово: false, 'Когда делаем': null },
        { Id: 3,  Готово: false, 'Когда делаем': '2026-09-02T10:00:00+03:00' } // просрочена
    ];
    const order = tasks.slice().sort(s.compareProjectTasks);
    assert.deepEqual(ids(order), [3, 1, 2, 30, 40]);
});

// ─────────────────────── Ленты: свежие сверху (UpdatedAt desc) ──────────────
test('Лента (История/Архив): свежие сверху, записи без UpdatedAt — в конец', () => {
    const rows = [
        { Id: 1, UpdatedAt: '2026-09-04T10:00:00+03:00' },
        { Id: 2 },                                        // нет даты — в конец
        { Id: 3, UpdatedAt: '2026-09-05T10:00:00+03:00' }
    ];
    const order = rows.slice().sort(s.compareByUpdatedAtDesc);
    assert.deepEqual(ids(order), [3, 1, 2]);
});

// ─────────────────────────── Справочники: алфавит ───────────────────────────
test('Контакты: алфавит по имени (ru), без учёта регистра/пробелов, пустые — в конец', () => {
    const contacts = [
        { Id: 1, Имя: 'василий' },
        { Id: 2, Имя: '' },
        { Id: 3, Имя: ' Борис ' },
        { Id: 4, Имя: 'Анна' }
    ];
    const order = contacts.slice().sort(s.compareContactsByName);
    assert.deepEqual(ids(order), [4, 3, 1, 2]);
});

test('Контакты: полностью одинаковые имена — выше старая запись (Id asc)', () => {
    const contacts = [
        { Id: 9, Имя: 'иван' },
        { Id: 2, Имя: 'Иван' }
    ];
    const order = contacts.slice().sort(s.compareContactsByName);
    assert.deepEqual(ids(order), [2, 9]);
});

test('Юрлица: сортируем по «Краткое Имя», при его отсутствии — по «Имя»', () => {
    const legals = [
        { Id: 1, 'Краткое Имя': 'ООО Вега' },
        { Id: 2, Имя: 'ООО Альфа' },   // без краткого — берём «Имя»
        { Id: 3, 'Краткое Имя': 'ООО Бета' }
    ];
    const order = legals.slice().sort(s.compareLegalsByName);
    assert.deepEqual(ids(order), [2, 3, 1]);
});

// ─────────────────── Проекты активные: этап → срок → свежесть ──────────────
test('Проекты: «Готов к сдаче» → «В работе» → «Обсуждение», внутри — по сроку', () => {
    const projects = [
        { Id: 1, Статус: 'В работе',     'Срок проекта': '2026-09-20' },
        { Id: 2, Статус: 'Готов к сдаче', 'Срок проекта': '2026-09-10' },
        { Id: 3, Статус: 'Обсуждение',    'Срок проекта': '2026-09-05' },
        { Id: 4, Статус: 'Готов к сдаче', 'Срок проекта': '2026-08-25' }, // просрочен
        { Id: 5, Статус: 'В работе',      'Срок проекта': null },         // без срока
        { Id: 6, Статус: 'В работе',      'Срок проекта': '2026-09-02' },
        { Id: 7, Статус: 'Готов к сдаче', 'Срок проекта': null },         // без срока
        { Id: 8, Статус: 'Обсуждение',    'Срок проекта': null }
    ];
    const order = projects.slice().sort(s.compareActiveProjectsByStage);
    assert.deepEqual(ids(order), [4, 2, 7, 6, 1, 5, 3, 8]);
});

test('Проекты: неизвестный статус (добавлен в NocoDB) — в конец, сортировку не ломает', () => {
    const projects = [
        { Id: 1, Статус: 'Суперважное' }, // не из PROJECT_ACTIVE_STAGES
        { Id: 2, Статус: 'Обсуждение', 'Срок проекта': '2026-09-05' },
        { Id: 3, Статус: 'В работе',   'Срок проекта': '2026-09-10' }
    ];
    const order = projects.slice().sort(s.compareActiveProjectsByStage);
    assert.deepEqual(ids(order), [3, 2, 1]);
});

test('Порядок этапов в модуле совпадает с договорённостью', () => {
    assert.deepEqual(s.PROJECT_ACTIVE_STAGES, ['Готов к сдаче', 'В работе', 'Обсуждение']);
});

