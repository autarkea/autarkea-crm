    if [ -n "$done_off" ]; then ts="'$(rel "$done_off" '18:00:00')'"; else ts='NULL'; fi
    tid=$(q "SELECT id FROM $T_TASK WHERE Что_делаем_ = '$nm' LIMIT 1;")
    if [ -z "$tid" ]; then
        tid=$(ins "$T_TASK" 'Что_делаем_, Когда_делаем, Готово, Когда_сделали_, created_at, updated_at' \
            "'$nm',$dl,$done_mark,$ts,'$NOW','$NOW'")
