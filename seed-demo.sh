    for t in 'nc_nw7q___Сотрудники' 'nc_nw7q___Проекты' 'nc_nw7q___Контакты' \
             'nc_nw7q___Юрлица' 'nc_nw7q___Позиции заказа' 'nc_nw7q___Дела' \
