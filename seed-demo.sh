# запустил в любой день — получил «живую» картину с задачами на сегодня/завтра
# и архивом за прошлые недели. Для повторных прогонов данные идемпотентны
# (поиск по названиям), но проще: ./seed-demo.sh --reset.
#
# Использование:
#   ./seed-demo.sh                 # наполнить (откажется, если данные уже есть)
#   ./seed-demo.sh --reset         # снапшот + очистка бизнес-данных + заливка
#   ./seed-demo.sh /путь/к/noco.db # своя база (по умолчанию песочница)
#
# ⚠️ Это инструмент разработки: он НЕ предназначен для клиентских установок и
# не трогает template.db. Все названия и реквизиты ВЫДУМАНЫ (безопасно для
