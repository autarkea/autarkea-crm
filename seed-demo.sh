add_doc() { # тип | статус | проект | дата_off | отправлен_off | примечание
    local ttype="$1" status="$2" project="$3" ddoc_off="$4" dsend_off="$5" note="$6"
    local dd ds nt did
    dd=$(rel "$ddoc_off")
    ds='NULL'; [ -n "$dsend_off" ] && ds="'$(rel "$dsend_off")'"
    nt='NULL'; [ -n "$note" ] && nt="'$note'"
    did=$(ins "$T_DOC" 'Тип_документа, Статус, Дата_документа, Дата_отправки, PDF_сгенерирован, С_печатью, Примечания, created_at, updated_at' \
        "'$ttype','$status','$dd',$ds,1,1,$nt,'$NOW','$NOW'")
    q "INSERT OR IGNORE INTO $J_DOC_PROJ (nc_nw7q___Проекты_id, nc_nw7q___Документы_id) VALUES ($project, $did);"
    # Подписант документа — Руководитель; кладовщик (для накладной) — Игорь
    q "INSERT OR IGNORE INTO $J_DOC_SIGN (nc_nw7q___Сотрудники_id, nc_nw7q___Документы_id) VALUES ($ADMIN_ID, $did);"
    if [ "$ttype" = 'Накладная' ]; then
        q "INSERT OR IGNORE INTO $J_DOC_STORE (nc_nw7q___Сотрудники_id, nc_nw7q___Документы_id) VALUES ($IGOR_ID, $did);"
    fi
}

