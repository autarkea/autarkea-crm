        q "SELECT 1 FROM sqlite_master WHERE type='table' AND name='$t' LIMIT 1;" | grep -q 1 \
            || { echo "❌ Таблица не найдена: $t (другая схема?)"; exit 1; }
    done
}

reset_data() {
