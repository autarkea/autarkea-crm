// ============================================================================
// shared/noco-fields.js — «список покупок» для горячих запросов к NocoDB (v4.68.0)
// ============================================================================
// Зачем. Без параметра `fields=` NocoDB разворачивает ВСЕ связи каждой строки
// (проекты, дела, документы, служебные M2M-списки) — ответ раздувается в разы.
// Это не теория, а замеры на dev-базе (4 сотрудника / 35 задач):
//
//   Сотрудники?limit=1000           — 60 788 Б → 1 111 Б    (×55)
//   Дела?limit=100&sort=-CreatedAt  — 99 025 Б → 14 340 Б   (×7)
//
// Оба запроса бот делает РАЗ В МИНУТУ (bot.js → setInterval(loadAllowedUsers, 60s)):
// кэш доступа/ролей и уведомления о новых задачах. Меньше трафика и меньше работы
// NocoDB — бот отзывается быстрее, сервер клиента не пыхтит вхолостую:
// ~160 КБ/мин → ~15 КБ/мин (≈230 МБ/сутки → ≈22 МБ/сутки на этой базе).
//
// Проверено на боевом API 2026.08.2: неизвестное поле в `fields=` не ломает запрос
// (отвечает 200, значение = null) — старые базы без новых колонок остаются рабочими.
//
// ⚠️ ПРАВИЛО: добавил чтение поля в горячий путь — добавь поле в список ЗДЕСЬ.
// Сторож — tests/noco-fields.test.js: он сверяет списки с тем, что реально читает код.
// Забыть поле опасно: значение придёт undefined (пример: «Активен» → деактивированный
// сотрудник снова получил бы доступ).
//
// Связи НЕ страдают: поле-связь из `fields=` по-прежнему отдаёт связанную запись
// (проверено на 2026.08.2: «Исполнитель» → {Id, ФИО}, «Какой проект» → с «Что делаем?»).
// ============================================================================

// Кэш сотрудников: ровно то, что кладётся в employeesCache, + Telegram_ID (ключ кэша)
// + «Активен» (фильтр isEmployeeActive). Флаг «Отправка документов» подставляется
// динамически (roles.DOCS_FLAG_FIELD) — см. вызов в bot.js.
const EMPLOYEE_CACHE_FIELDS = [
    'Id',
    'ФИО',
    'Обращение',
    'Роль',
    'Должность',
    'Telegram_ID',
    'Активен'
];

// Горячий путь уведомлений о новых задачах (раз в 60 сек)
const TASK_NOTIFY_FIELDS = [
    'Id',
    'Что делаем?',
    'Когда делаем',
    'Готово',
    'CreatedAt',
    'Исполнитель',
    'Какой проект'
];

// Строка запроса: `fields=A,B,C` (кириллица — percent-encoding, иначе NocoDB не поймёт).
// extra — для динамических имён (например roles.DOCS_FLAG_FIELD).
function fieldsParam(fields, extra = []) {
    return 'fields=' + [...fields, ...extra].map(encodeURIComponent).join(',');
}

module.exports = { EMPLOYEE_CACHE_FIELDS, TASK_NOTIFY_FIELDS, fieldsParam };
