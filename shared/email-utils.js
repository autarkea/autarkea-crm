// ============================================================================
// shared/email-utils.js — проверка и выбор email для отправки документов
// ============================================================================
// Зачем: поле «E-mail» в карточках (Сотрудники/Контакты/Юрлица) — это свободный
// текст. Оператор может опечататься, вставить «нет», «-», оставить пробел. Такой
// адрес нельзя пускать в заголовки письма:
//   • Reply-To с мусором (напр. «нет») заставляет SMTP отклонить письмо ЦЕЛИКОМ —
//     то есть клиент не получит документ из-за чужой опечатки в справочнике;
//   • адрес-«чужак» в скрытой копии — риск утечки документа.
// Поэтому: берём адрес только если он похож на email, иначе — безопасный fallback
// (общий ящик компании SMTP_FROM).
//
// v4.64.4: скрытая копия (Bcc) убрана совсем (Вариант А) — остаётся только
// Reply-To (клиент отвечает менеджеру) и подпись.
//
// Тесты: tests/email-utils.test.js
// ============================================================================

// Простая проверка «похоже на email»: непустые части, ровно одна @, точка в
// домене, без пробелов. Полный RFC 5322 не нужен — задача отсечь мусор, а не
// валидировать экзотику; финальную доставляемость всё равно решает SMTP.
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

// true, если значение похоже на email (после обрезки пробелов).
function isValidEmail(value) {
    return EMAIL_RE.test(String(value == null ? '' : value).trim());
}

// Возвращает обрезанный адрес, если он похож на email; иначе — fallback.
// Никогда не бросает и всегда возвращает строку.
function pickEmail(value, fallback = '') {
    const v = String(value == null ? '' : value).trim();
    return EMAIL_RE.test(v) ? v : String(fallback == null ? '' : fallback);
}

module.exports = { EMAIL_RE, isValidEmail, pickEmail };
