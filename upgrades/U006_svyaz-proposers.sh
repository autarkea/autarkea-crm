#!/bin/bash
# upgrades/U006_svyaz-proposers.sh
# Связь «Кто предложил» (Дела → Сотрудники) + обратная «Предложенные дела» (Сотрудники → Дела)
# Через add-link-m2o.sh (M2O + промежуточная M2M, имя с обработкой коллизий)
#
# Имя обратной связи: до v4.67.0 было сырое «Делаs» (модуль лепил «s» к названию
# таблицы) — на живых установках его переименовывает дельта U011. Новые применения
# дельты (установки со схемой < 6) сразу получают человеческое имя.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

echo "📦 U006: Связь Дела.Кто предложил ↔ Сотрудники.Предложенные дела"
bash modules/add-link-m2o.sh "Дела" "Кто предложил" "Сотрудники" "Предложенные дела" || exit 1
echo "✅ U006 завершена"
